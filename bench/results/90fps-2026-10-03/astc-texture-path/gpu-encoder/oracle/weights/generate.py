#!/usr/bin/env python3
"""Reproduce Basis ASTC 8x8 <- 5x5 weight interpolation and GLSL pinv."""
import numpy as np
from pathlib import Path

OUT = Path(__file__).resolve().parent

def basis_samples(block=8, grid=5):
    # Exact integer expressions from basisu_astc_helpers.h::compute_upsample_weights.
    sx = (1024 + block // 2) // (block - 1)
    sy = sx
    rows = []
    for ty in range(block):
        for tx in range(block):
            gx = (sx * tx * (grid - 1) + 32) >> 6
            gy = (sy * ty * (grid - 1) + 32) >> 6
            jx, jy, fx, fy = gx >> 4, gy >> 4, gx & 15, gy & 15
            w11 = (fx * fy + 8) >> 4
            w10, w01 = fy - w11, fx - w11
            w00 = 16 - fx - fy + w11
            row = np.zeros(grid * grid, dtype=np.float64)
            for dy, dx, w in ((0, 0, w00), (0, 1, w01), (1, 0, w10), (1, 1, w11)):
                if w:
                    row[(jy + dy) * grid + jx + dx] += w / 16.0
            assert abs(row.sum() - 1.0) < 1e-12
            rows.append(row)
    return np.array(rows)

def main():
    a = basis_samples()
    b = np.linalg.pinv(a)
    assert np.linalg.matrix_rank(a) == 25
    assert np.max(np.abs(b @ a - np.eye(25))) < 1e-12
    np.savetxt(OUT / "A.csv", a, delimiter=",", fmt="%.8f")
    with (OUT / "inverse.glsl").open("w") as f:
        f.write("// Generated by generate.py; row-major [gridWeight][texel].\n")
        f.write("const float astc5x5InverseA[1600] = float[1600](\n")
        vals = b.reshape(-1)
        for i in range(0, len(vals), 8):
            f.write("    " + ", ".join(f"{v:.9g}" for v in vals[i:i+8]))
            f.write(",\n" if i + 8 < len(vals) else "\n")
        f.write(");\n")
    # Constant preservation and recovery of a source-plane ramp through A then B.
    one = np.ones(25)
    assert np.max(np.abs(b @ (a @ one) - one)) < 1e-12
    ramp = np.arange(25, dtype=np.float64)
    assert np.max(np.abs(b @ (a @ ramp) - ramp)) < 1e-11
    print(f"shape={a.shape} rank={np.linalg.matrix_rank(a)}")
    print(f"row_sum_error={np.max(np.abs(a.sum(axis=1)-1)):.3g}")
    print(f"max_abs_BA_minus_I={np.max(np.abs(b@a-np.eye(25))):.3g}")
    print(f"max_constant_error={np.max(np.abs(b@(a@one)-one)):.3g}")
    print(f"max_ramp_error={np.max(np.abs(b@(a@ramp)-ramp)):.3g}")

if __name__ == "__main__":
    main()
