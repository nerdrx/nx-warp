const uint8_t *nxe_scan_table(int n, int tskip) {
    if (n == 64) return tskip ? nxe_raster8 : nxe_zigzag8;
    if (n == 16) return nxe_zigzag4;
    if (n == 4) return nxe_zigzag2;
    return nxe_zigzag1;
}

int nxe_last_class_of(int pos) {
    int c;
    for (c = 14; c >= 0; --c)
        if (pos >= (int)nxe_last_base[c]) return c;
    return 0;
}
